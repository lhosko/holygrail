def _messages(context, inference_input):
    level = str(context.vars.get("level", "2"))
    messages = [{"role": "system", "content": SYSTEM_PROMPTS.get(level, SYSTEM_PROMPTS["2"])}]
    history = getattr(inference_input, "messages", None) or []
    for msg in history:
        if msg.role in ("user", "assistant"):
            messages.append({"role": msg.role, "content": msg.content})
    if len(messages) == 1:
        messages.append({"role": "user", "content": inference_input.prompt})
    return messages


